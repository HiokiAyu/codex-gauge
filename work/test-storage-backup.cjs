const assert=require('node:assert/strict');
const fs=require('node:fs');
const os=require('node:os');
const path=require('node:path');
const {DatabaseSync}=require('node:sqlite');
const {makeBackup,readBackup,restoreBackup,restoreById,listBackups,resumeRestore,prepareStorage}=require('./CodexDashboard/storage-backup');
const root=fs.mkdtempSync(path.join(os.tmpdir(),'dashboard-storage-'));
let db;
try{
 fs.writeFileSync(path.join(root,'preferences.json'),'\uFEFF'+JSON.stringify({language:'en'}));
 fs.writeFileSync(path.join(root,'credentials.json'),'PRIVATE_CREDENTIAL');
 fs.mkdirSync(path.join(root,'log-cache'));
 fs.writeFileSync(path.join(root,'log-cache','private.jsonl'),'PRIVATE_CHAT');
 const database=path.join(root,'calibration.sqlite');
 db=new DatabaseSync(database);
 db.exec("PRAGMA journal_mode=WAL;CREATE TABLE events(id INTEGER PRIMARY KEY,value TEXT);INSERT INTO events VALUES(1,'before')");
 const preparation=prepareStorage(root,'1.0.0-rc.1');
 assert(preparation.backup);
 const manifest=readBackup(preparation.backup);
 assert.equal(manifest.files.length,2);
 assert(!JSON.stringify(manifest).includes('credentials'));
 preparation.finalize();
 assert.equal(prepareStorage(root,'1.0.0-rc.1').finalize,undefined);
 db.exec("UPDATE events SET value='after'");
 db.close();db=null;
 fs.writeFileSync(path.join(root,'preferences.json'),JSON.stringify({language:'ja'}));
 fs.writeFileSync(path.join(root,'workload-abcdef.json'),'{"newer":true}');
 const extra=new DatabaseSync(path.join(root,'calibration-source-abcdef.sqlite'));
 extra.exec('CREATE TABLE newer(id INTEGER)');extra.close();
 assert(listBackups(root).some(item=>item.id===path.basename(preparation.backup)));
 assert(!JSON.stringify(listBackups(root)).includes(root));
 assert.throws(()=>restoreById(root,'../outside'),/identifier/);
 const restored=restoreBackup(root,preparation.backup);
 assert(!fs.existsSync(path.join(root,'workload-abcdef.json')));
 assert(!fs.existsSync(path.join(root,'calibration-source-abcdef.sqlite')));
 assert(fs.existsSync(path.join(restored.recovery,'workload-abcdef.json')));
 assert(restored.recovery);
 assert.equal(JSON.parse(fs.readFileSync(path.join(root,'preferences.json'),'utf8').replace(/^\uFEFF/,'')).language,'en');
 db=new DatabaseSync(database);
 assert.equal(db.prepare('SELECT value FROM events').get().value,'before');
 db.close();db=null;
 assert.equal(fs.readFileSync(path.join(root,'credentials.json'),'utf8'),'PRIVATE_CREDENTIAL');
 fs.writeFileSync(database,'corrupted database');
 assert(restoreBackup(root,preparation.backup).restored.includes('calibration.sqlite'));
 db=new DatabaseSync(database);assert.equal(db.prepare('SELECT count(*) n FROM events').get().n,1);db.close();db=null;
 const recovery=makeBackup(root,'before-test');
 fs.writeFileSync(path.join(root,'preferences.json'),'{}');
 fs.writeFileSync(path.join(root,'restore-pending.json'),JSON.stringify({backup:preparation.backup,recovery}));
 assert(resumeRestore(root));
 assert(!fs.existsSync(path.join(root,'restore-pending.json')));
 assert.equal(JSON.parse(fs.readFileSync(path.join(root,'preferences.json'),'utf8').replace(/^\uFEFF/,'')).language,'en');
 fs.appendFileSync(path.join(preparation.backup,'preferences.json'),'x');
 assert.throws(()=>readBackup(preparation.backup),/checksum/);
 assert(!listBackups(root).some(item=>item.id===path.basename(preparation.backup)));
 const cp=require('node:child_process');
 const cli=cp.spawnSync(process.execPath,[path.join(__dirname,'CodexDashboard/storage-backup.js'),'--restore',path.basename(recovery),root],{encoding:'utf8',windowsHide:true});
 assert.equal(cli.status,0,cli.stderr);
 assert.equal(JSON.parse(cli.stdout).success,true);
 console.log('Passed: WAL-consistent migration backup, checksum validation, damaged-data recovery and interrupted-restore replay.');
}finally{
 db?.close();
 fs.rmSync(root,{recursive:true,force:true});
}
